//! Installing a version: JSON, client jar, libraries, logging config, assets.

use crate::config::Dirs;
use crate::download::{DownloadTask, Downloader, ProgressFn};
use crate::version::{
    self, resolve_libraries, ResolvedVersion, RuleContext, VersionJson, VersionManifest,
    MANIFEST_URL,
};
use crate::{paths, Error, Result};
use serde::Deserialize;
use std::collections::HashMap;

pub const RESOURCES_URL: &str = "https://resources.download.minecraft.net";

#[derive(Debug, Clone, Deserialize)]
pub struct AssetIndex {
    pub objects: HashMap<String, AssetObject>,
    /// Pre-1.7 style: files live under `assets/virtual/<id>`.
    #[serde(default, rename = "virtual")]
    pub is_virtual: bool,
    /// Pre-1.6 style: files must be copied into `<gameDir>/resources`.
    #[serde(default)]
    pub map_to_resources: bool,
}

#[derive(Debug, Clone, Deserialize)]
pub struct AssetObject {
    pub hash: String,
    pub size: u64,
}

fn valid_hash(h: &str) -> bool {
    h.len() == 40 && h.chars().all(|c| c.is_ascii_hexdigit())
}

pub async fn fetch_manifest(dl: &Downloader) -> Result<VersionManifest> {
    dl.fetch_json(MANIFEST_URL).await
}

/// Make sure `<versions>/<id>/<id>.json` exists for `id` and everything it
/// inherits from. Locally-created versions (loader profiles) are trusted as is.
async fn ensure_version_jsons(dl: &Downloader, dirs: &Dirs, id: &str) -> Result<()> {
    let mut manifest: Option<VersionManifest> = None;
    let mut current = id.to_string();
    for _ in 0..8 {
        let path = version::version_json_path(&dirs.versions(), &current)?;
        if !path.is_file() {
            if manifest.is_none() {
                manifest = Some(fetch_manifest(dl).await?);
            }
            let entry = manifest
                .as_ref()
                .and_then(|m| m.find(&current))
                .ok_or_else(|| Error::VersionNotFound(current.clone()))?;
            let task = DownloadTask::new(entry.url.clone(), path.clone()).sha1(entry.sha1.clone());
            dl.download_all(vec![task], "版本信息", None).await?;
        }
        let v: VersionJson = serde_json::from_slice(&std::fs::read(&path)?)?;
        match v.inherits_from {
            Some(p) => current = p,
            None => return Ok(()),
        }
    }
    Err(Error::Other("版本继承链过深".into()))
}

/// Which Java `id` needs and whether it is installed. Only the small version
/// descriptions are fetched (when missing); nothing else is downloaded.
pub async fn java_need(dl: &Downloader, dirs: &Dirs, id: &str) -> Result<crate::java::JavaNeed> {
    ensure_version_jsons(dl, dirs, id).await?;
    crate::java::need_for(dirs, &version::load_resolved(&dirs.versions(), id)?)
}

/// Downloads for libraries; files without a source (generated by a loader's
/// installer) are skipped, they only need to exist.
fn library_tasks(dirs: &Dirs, libs: &[crate::version::LibFile]) -> Result<Vec<DownloadTask>> {
    libs.iter()
        .filter(|lib| !lib.url.is_empty())
        .map(|lib| {
            Ok(DownloadTask::rel(&dirs.libraries(), &lib.rel_path, lib.url.clone())?
                .sha1(lib.sha1.clone())
                .size(lib.size)
                .sidecar(lib.sidecar && lib.sha1.is_none()))
        })
        .collect()
}

/// Download everything needed to launch `id`. Safe to call repeatedly: files
/// that are already present are skipped.
pub async fn install_version(
    dl: &Downloader,
    dirs: &Dirs,
    id: &str,
    progress: Option<ProgressFn>,
) -> Result<ResolvedVersion> {
    ensure_version_jsons(dl, dirs, id).await?;
    let resolved = version::load_resolved(&dirs.versions(), id)?;
    let v = &resolved.json;
    let ctx = RuleContext::current();

    let mut core: Vec<DownloadTask> = Vec::new();

    // client.jar (lives under the root of the inheritance chain)
    let client = v
        .downloads
        .as_ref()
        .and_then(|d| d.client.as_ref())
        .ok_or_else(|| Error::Other(format!("版本 {id} 缺少 client 下载信息")))?;
    let jar = version::version_json_path(&dirs.versions(), &resolved.jar_id)?.with_extension("jar");
    core.push(
        DownloadTask::new(client.url.clone(), jar).sha1(client.sha1.clone()).size(client.size),
    );

    // libraries
    core.extend(library_tasks(dirs, &resolve_libraries(v, &ctx))?);

    // log4j configuration (Log4Shell mitigation for 1.7 - 1.18.0)
    if let Some(c) = v.logging.as_ref().and_then(|l| l.client.as_ref()) {
        core.push(
            DownloadTask::rel(&dirs.assets().join("log_configs"), &c.file.id, c.file.url.clone())?
                .sha1(c.file.sha1.clone())
                .size(c.file.size),
        );
    }

    // asset index
    let index_ref = v
        .asset_index
        .as_ref()
        .ok_or_else(|| Error::Other(format!("版本 {id} 缺少 assetIndex")))?;
    let index_path = paths::safe_join(&dirs.assets().join("indexes"), &format!("{}.json", index_ref.id))?;
    dl.download_all(
        vec![DownloadTask::new(index_ref.url.clone(), index_path.clone())
            .sha1(index_ref.sha1.clone())
            .size(index_ref.size)],
        "资源索引",
        None,
    )
    .await?;
    let index: AssetIndex = serde_json::from_slice(&std::fs::read(&index_path)?)?;

    dl.download_all(core, "游戏文件", progress.clone()).await?;

    let objects_dir = dirs.assets().join("objects");
    let mut assets = Vec::with_capacity(index.objects.len());
    for (name, obj) in &index.objects {
        if !valid_hash(&obj.hash) {
            return Err(Error::Other(format!("资源 {name} 的 hash 无效: {}", obj.hash)));
        }
        let prefix = &obj.hash[..2];
        assets.push(
            DownloadTask::rel(&objects_dir, &format!("{prefix}/{}", obj.hash), format!("{RESOURCES_URL}/{prefix}/{}", obj.hash))?
                .sha1(Some(obj.hash.clone()))
                .size(Some(obj.size)),
        );
    }
    dl.download_all(assets, "游戏资源", progress).await?;

    Ok(resolved)
}

pub fn load_asset_index(dirs: &Dirs, id: &str) -> Result<AssetIndex> {
    let p = paths::safe_join(&dirs.assets().join("indexes"), &format!("{id}.json"))?;
    let bytes = std::fs::read(&p).map_err(|_| Error::Missing(p))?;
    Ok(serde_json::from_slice(&bytes)?)
}

#[cfg(test)]
mod tests {
    #[test]
    fn libraries_without_a_url_are_not_downloaded() {
        use crate::version::LibFile;
        let lib = |rel: &str, url: &str| LibFile {
            key: rel.into(),
            rel_path: rel.into(),
            url: url.into(),
            sha1: None,
            size: None,
            sidecar: false,
            on_classpath: true,
            extract: false,
            extract_exclude: vec![],
        };
        let dirs = Dirs::new("C:/d");
        let tasks = library_tasks(&dirs, &[lib("a/a.jar", "https://x/a.jar"), lib("f/f-client.jar", "")]).unwrap();
        assert_eq!(tasks.len(), 1);
        assert!(tasks[0].dest.ends_with("a/a.jar"));
    }

    use super::*;

    #[test]
    fn hash_validation() {
        assert!(valid_hash("bdf48ef6b5d0d23bbb02e17d04865216179f510a"));
        assert!(!valid_hash("../etc/passwd"));
        assert!(!valid_hash("bdf4"));
    }

    #[test]
    fn asset_index_flags_parse() {
        let idx: AssetIndex = serde_json::from_str(
            r#"{"objects":{"a":{"hash":"bdf48ef6b5d0d23bbb02e17d04865216179f510a","size":3}},"virtual":true}"#,
        )
        .unwrap();
        assert!(idx.is_virtual && !idx.map_to_resources);
    }
}
